#!/usr/bin/env node
/**
 * pr-auto-rebase.mjs -- keep conflicted PRs from sitting.
 *
 * For each open PR whose mergeStateStatus is DIRTY (the signal
 * check-pr-mergeable.mjs reads as mergeable=CONFLICTING), try a rebase onto
 * origin/main in a checkout. Clean: push with --force-with-lease to the PR
 * branch only. Conflict: abort, label `needs-rebase`, ONE comment per head SHA
 * listing the conflicted files. No longer DIRTY: remove the label.
 *
 * Skips: drafts, fork PRs, PRs touched in the last 10 minutes. Cap: 5 per run.
 * Never pushes main. `--dry-run` decides and reports, writes nothing.
 *
 * Exit: 0 ran (whatever the outcomes), 2 could not run (no token, no
 * repo, GitHub unreachable). Never 1: there is no contract to violate here.
 *
 *   node scripts/pr-auto-rebase.mjs [--dry-run]
 *   node scripts/pr-auto-rebase.mjs --self-test
 */
import { execFileSync } from 'node:child_process';
import { isEntryPoint } from './lib/entry-point.mjs';
import { parseRepoSlug } from './check-pr-mergeable.mjs';

export const LABEL = 'needs-rebase';
export const CAP = 5;
export const QUIET_MINUTES = 10;
const MARKER = 'pr-auto-rebase:conflict';
const BASE_BRANCH = 'main';
// Never run repo hooks from a PR branch's checkout in the bot's environment.
const HOOKS_OFF = ['-c', 'core.hooksPath=/dev/null'];

export function commentMarker(sha) {
  return '<!-- ' + MARKER + ' sha=' + sha + ' -->';
}

/** Pure decision for one PR. Returns { action, reason }. */
export function decide(pr, { nowMs }) {
  const hasLabel = (pr.labels ?? []).includes(LABEL);
  if (pr.mergeStateStatus !== 'DIRTY') {
    return { action: hasLabel ? 'unlabel' : 'skip', reason: 'not DIRTY' };
  }
  if (pr.isDraft) return { action: 'skip', reason: 'draft' };
  if (pr.headRefName === BASE_BRANCH) return { action: 'skip', reason: 'head is main' };
  if (pr.baseRefName !== BASE_BRANCH) return { action: 'skip', reason: 'base is not main (stacked)' };
  if (pr.isCrossRepository) return { action: 'skip', reason: 'fork' };
  const touched = Date.parse(pr.updatedAt);
  if (Number.isFinite(touched) && (nowMs - touched) / 60000 < QUIET_MINUTES) {
    return { action: 'skip', reason: 'touched in last ' + QUIET_MINUTES + ' min' };
  }
  const flagged =
    hasLabel && (pr.commentBodies ?? []).some((b) => b.includes(commentMarker(pr.headOid)));
  if (flagged) return { action: 'skip', reason: 'already flagged for this head' };
  return { action: 'rebase', reason: 'DIRTY' };
}

/**
 * Process the PR list. deps: { git, rebase(pr)->{ok,files}, push(pr), label(n),
 * unlabel(n), comment(n, body), now }. Returns the report array.
 */
export async function processAll(prs, deps, { dryRun = false } = {}) {
  const report = [];
  let handled = 0;
  for (const pr of prs) {
    const d = decide(pr, { nowMs: deps.now() });
    const row = { number: pr.number, action: d.action, reason: d.reason, result: '' };
    if (d.action === 'unlabel') {
      if (!dryRun) await deps.unlabel(pr.number);
      row.result = dryRun ? 'would remove label' : 'label removed';
    } else if (d.action === 'rebase') {
      if (handled >= CAP) {
        row.action = 'skip';
        row.reason = 'cap ' + CAP + ' per run';
        report.push(row);
        continue;
      }
      handled += 1;
      try {
        await rebaseOne(pr, row);
      } catch (e) {
        row.result = 'ERROR: ' + String(e.message ?? e).split('\n')[0].slice(0, 200);
      } finally {
        if (deps.cleanup) {
          try {
            await deps.cleanup(pr);
          } catch (cleanupErr) {
            console.error('cleanup failed for #' + pr.number + ': ' + cleanupErr.message);
          }
        }
      }
    }
    report.push(row);
  }
  return report;

  async function rebaseOne(pr, row) {
      const r = await deps.rebase(pr);
      if (r.ok) {
        if (!dryRun) await deps.push(pr);
        row.result = dryRun ? 'clean rebase (not pushed, dry run)' : 'rebased and pushed';
      } else {
        const marker = commentMarker(pr.headOid);
        const already = (pr.commentBodies ?? []).some((b) => b.includes(marker));
        const labelled = (pr.labels ?? []).includes(LABEL);
        if (!dryRun) {
          if (!labelled) await deps.label(pr.number);
          if (!already) {
            await deps.comment(
              pr.number,
              marker +
                '\nAuto-rebase onto `main` hit a real conflict in:\n\n' +
                r.files.map((f) => '- `' + f + '`').join('\n') +
                '\n\nPlease rebase by hand. This comment is posted once per head commit.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
            );
          }
        }
        row.result =
          'conflict in ' + r.files.length + ' file(s): ' + r.files.join(', ') +
          (dryRun ? ' (dry run, nothing written)' : already ? ' (comment already posted)' : ' (labelled + commented)');
      }
  }
}

function sh(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

/** Real-git rebase of one PR branch in cwd. Aborts on conflict. */
export function gitRebase(pr, cwd, rawRun = sh) {
  const run = (args, dir) => rawRun([...HOOKS_OFF, ...args], dir);
  run(['fetch', '--quiet', 'origin', 'main'], cwd);
  run(['fetch', '--quiet', 'origin', pr.headRefName], cwd);
  run(['checkout', '--quiet', '-B', 'rebase-work', 'FETCH_HEAD'], cwd);
  try {
    run(['rebase', 'origin/main'], cwd);
    return { ok: true, files: [] };
  } catch (e) {
    let files = [];
    try {
      files = run(['diff', '--name-only', '--diff-filter=U'], cwd).split('\n').filter(Boolean);
    } finally {
      try {
        run(['rebase', '--abort'], cwd);
      } catch (abortErr) {
        console.error('rebase --abort failed: ' + abortErr.message);
      }
    }
    if (files.length === 0) throw new Error('rebase failed with no conflicted files: ' + String(e.stderr ?? e.message));
    return { ok: false, files };
  }
}

const LIST_QUERY = `query($owner:String!,$name:String!){repository(owner:$owner,name:$name){
 pullRequests(states:OPEN,first:100,orderBy:{field:UPDATED_AT,direction:DESC}){nodes{
  number isDraft isCrossRepository mergeStateStatus updatedAt headRefName headRefOid baseRefName
  labels(first:30){nodes{name}}}}}}`;

async function api(token, url, init = {}) {
  const res = await fetch(url, {
    ...init,
    headers: { authorization: 'Bearer ' + token, accept: 'application/vnd.github+json', ...(init.headers ?? {}) },
  });
  if (!res.ok && res.status !== 422) throw new Error('GitHub ' + res.status + ' for ' + url);
  return res;
}

/** All issue-comment bodies for a PR, every page (no 50-comment window). */
export async function fetchCommentBodies(token, base, n, apiFn = api) {
  const bodies = [];
  for (let page = 1; page <= 50; page++) {
    const res = await apiFn(token, base + '/issues/' + n + '/comments?per_page=100&page=' + page);
    const batch = await res.json();
    if (!Array.isArray(batch)) throw new Error('comments list for #' + n + ' was not an array');
    for (const c of batch) bodies.push(String(c.body ?? ''));
    if (batch.length < 100) break;
  }
  return bodies;
}

async function listOpenPrs(token, slug) {
  // mergeStateStatus is computed lazily: first read can be UNKNOWN. One retry.
  for (let attempt = 0; attempt < 2; attempt++) {
    const res = await api(token, 'https://api.github.com/graphql', {
      method: 'POST',
      body: JSON.stringify({ query: LIST_QUERY, variables: { owner: slug.owner, name: slug.name } }),
    });
    const json = await res.json();
    if (json.errors) throw new Error('GraphQL: ' + JSON.stringify(json.errors).slice(0, 300));
    const nodes = json.data.repository.pullRequests.nodes.map((n) => ({
      number: n.number,
      isDraft: n.isDraft,
      isCrossRepository: n.isCrossRepository,
      mergeStateStatus: n.mergeStateStatus,
      updatedAt: n.updatedAt,
      headRefName: n.headRefName,
      baseRefName: n.baseRefName,
      headOid: n.headRefOid,
      labels: n.labels.nodes.map((l) => l.name),
      commentBodies: [],
    }));
    if (attempt === 1 || !nodes.some((p) => p.mergeStateStatus === 'UNKNOWN')) return nodes;
    await new Promise((r) => setTimeout(r, 4000));
  }
  return [];
}

export async function main(argv, env = process.env) {
  const dryRun = argv.includes('--dry-run');
  const token = env.GITHUB_TOKEN;
  if (!token) {
    console.error('pr-auto-rebase: GITHUB_TOKEN (the bot PAT) is not set. Exit 2: cannot run.');
    return 2;
  }
  let slug;
  try {
    slug = parseRepoSlug(env.GITHUB_REPOSITORY ? 'https://github.com/' + env.GITHUB_REPOSITORY + '.git' : sh(['remote', 'get-url', 'origin']).trim());
  } catch (e) {
    console.error('pr-auto-rebase: cannot determine repo: ' + e.message);
    return 2;
  }
  if (!slug) {
    console.error('pr-auto-rebase: cannot determine repo slug.');
    return 2;
  }
  const base = 'https://api.github.com/repos/' + slug.owner + '/' + slug.name;
  let prs;
  try {
    prs = await listOpenPrs(token, slug);
  } catch (e) {
    console.error('pr-auto-rebase: ' + e.message);
    return 2;
  }
  for (const pr of prs) {
    // Only PRs that could reach the label/comment path need their comments.
    if (pr.mergeStateStatus !== 'DIRTY' || pr.isDraft || pr.isCrossRepository) continue;
    try {
      pr.commentBodies = await fetchCommentBodies(token, base, pr.number);
    } catch (e) {
      console.error('pr-auto-rebase: comments for #' + pr.number + ': ' + e.message + ' (PR skipped this run)');
      pr.isDraft = true; // fail closed: without the comment list we cannot keep one-comment-per-SHA
    }
  }
  const cwd = process.cwd();
  const deps = {
    now: () => Date.now(),
    rebase: async (pr) => gitRebase(pr, cwd),
    cleanup: async () => {
      try {
        sh([...HOOKS_OFF, 'rebase', '--abort'], cwd);
      } catch {
        /* no rebase in progress */
      }
    },
    push: async (pr) => {
      sh([...HOOKS_OFF, 'push', 'origin', 'rebase-work:refs/heads/' + pr.headRefName, '--force-with-lease=refs/heads/' + pr.headRefName + ':' + pr.headOid], cwd);
    },
    label: async (n) => {
      await api(token, base + '/labels', {
        method: 'POST',
        body: JSON.stringify({ name: LABEL, color: 'd93f0b', description: 'Conflicts with main; auto-rebase could not fix it' }),
      }); // 422 (already exists) is tolerated by api()
      await api(token, base + '/issues/' + n + '/labels', { method: 'POST', body: JSON.stringify({ labels: [LABEL] }) });
    },
    unlabel: async (n) => {
      const res = await fetch(base + '/issues/' + n + '/labels/' + LABEL, {
        method: 'DELETE',
        headers: { authorization: 'Bearer ' + token, accept: 'application/vnd.github+json' },
      });
      if (!res.ok && res.status !== 404) throw new Error('unlabel ' + n + ': HTTP ' + res.status);
    },
    comment: async (n, body) => {
      await api(token, base + '/issues/' + n + '/comments', { method: 'POST', body: JSON.stringify({ body }) });
    },
  };
  const report = await processAll(prs, deps, { dryRun });
  console.log('pr-auto-rebase' + (dryRun ? ' (DRY RUN)' : '') + ': ' + prs.length + ' open PR(s)');
  for (const r of report) {
    if (r.action === 'skip' && r.reason === 'not DIRTY') continue;
    console.log('  #' + r.number + ' ' + r.action + ' -- ' + r.reason + (r.result ? ' -- ' + r.result : ''));
  }
  if (!report.some((r) => r.action !== 'skip' || r.reason !== 'not DIRTY')) console.log('  nothing DIRTY.');
  return 0;
}

// ---------------------------------------------------------------- self-test
async function selfTest() {
  const assert = (cond, msg) => {
    if (!cond) throw new Error('FAIL: ' + msg);
  };
  const NOW = Date.parse('2026-11-19T12:00:00Z');
  const old = '2026-11-19T11:00:00Z';
  const mk = (over) => ({
    number: 1, isDraft: false, isCrossRepository: false, baseRefName: 'main', mergeStateStatus: 'DIRTY',
    updatedAt: old, headRefName: 'b', headOid: 'sha1', labels: [], commentBodies: [], ...over,
  });
  const mkDeps = (rebaseResult) => {
    const calls = [];
    return {
      calls,
      now: () => NOW,
      rebase: async (pr) => { calls.push('rebase#' + pr.number); return rebaseResult; },
      push: async (pr) => { calls.push('push#' + pr.number); },
      label: async (n) => { calls.push('label#' + n); },
      unlabel: async (n) => { calls.push('unlabel#' + n); },
      comment: async (n, b) => { calls.push('comment#' + n); calls.body = b; },
    };
  };
  const cases = [];
  const t = (name, fn) => cases.push([name, fn]);

  t('clean rebase pushes, no label/comment', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({})], d);
    assert(d.calls.join() === 'rebase#1,push#1', d.calls.join());
  });
  t('conflict labels once and comments once, never pushes', async () => {
    const d = mkDeps({ ok: false, files: ['a.ts', 'b.ts'] });
    await processAll([mk({})], d);
    assert(d.calls.join() === 'rebase#1,label#1,comment#1', d.calls.join());
    assert(d.calls.body.includes('a.ts') && d.calls.body.includes(commentMarker('sha1')), 'body lists files + marker');
  });
  t('idempotent: same head SHA already commented -> no second comment', async () => {
    const d = mkDeps({ ok: false, files: ['a.ts'] });
    await processAll([mk({ commentBodies: [commentMarker('sha1') + ' old'] })], d);
    assert(d.calls.join() === 'rebase#1,label#1', d.calls.join());
  });
  t('new head SHA gets a fresh comment', async () => {
    const d = mkDeps({ ok: false, files: ['a.ts'] });
    await processAll([mk({ headOid: 'sha2', labels: [LABEL], commentBodies: [commentMarker('sha1')] })], d);
    assert(d.calls.join() === 'rebase#1,comment#1', d.calls.join());
  });
  t('flagged PR (label + marker for head SHA) is skipped and does not use the cap', async () => {
    const d = mkDeps({ ok: true, files: [] });
    const flagged = [1, 2, 3, 4, 5, 6].map((n) => mk({ number: n, labels: [LABEL], commentBodies: [commentMarker('sha1')] }));
    const rep = await processAll([...flagged, mk({ number: 9 })], d);
    assert(d.calls.join() === 'rebase#9,push#9', d.calls.join());
    assert(rep[0].reason === 'already flagged for this head', rep[0].reason);
  });
  t('error on one PR is recorded, cleanup runs, next PR still processed', async () => {
    const d = mkDeps({ ok: true, files: [] });
    d.push = async (pr) => { d.calls.push('push#' + pr.number); if (pr.number === 1) throw new Error('stale info'); };
    d.cleanup = async (pr) => { d.calls.push('cleanup#' + pr.number); };
    const rep = await processAll([mk({}), mk({ number: 2 })], d);
    assert(d.calls.join() === 'rebase#1,push#1,cleanup#1,rebase#2,push#2,cleanup#2', d.calls.join());
    assert(rep[0].result.startsWith('ERROR: stale info'), rep[0].result);
    assert(rep[1].result === 'rebased and pushed', rep[1].result);
  });
  t('comments are paginated: marker on page 2 is found', async () => {
    const pages = [
      Array.from({ length: 100 }, (_, i) => ({ body: 'c' + i })),
      [{ body: commentMarker('sha1') }],
    ];
    const seen = [];
    const fake = async (_t, url) => {
      seen.push(url);
      const page = Number(/&page=(\d+)/.exec(url)[1]);
      return { json: async () => pages[page - 1] ?? [] };
    };
    const bodies = await fetchCommentBodies('t', 'https://x', 5, fake);
    assert(bodies.length === 101 && seen.length === 2, 'got ' + bodies.length + ' in ' + seen.length + ' pages');
    assert(bodies.some((b) => b.includes(commentMarker('sha1'))), 'marker found');
  });
  t('PR whose base is not main (stacked) is untouched', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ baseRefName: 'feature-x' })], d);
    assert(d.calls.length === 0, d.calls.join());
  });
  t('PR whose head branch is main is untouched', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ headRefName: 'main' })], d);
    assert(d.calls.length === 0, d.calls.join());
  });
  t('every git call from gitRebase has hooks disabled', async () => {
    const seen = [];
    const run = (args) => { seen.push(args); return ''; };
    gitRebase({ headRefName: 'b' }, '.', run);
    assert(seen.length >= 4 && seen.every((a) => a[0] === '-c' && a[1] === 'core.hooksPath=/dev/null'), JSON.stringify(seen));
  });
  t('draft is untouched', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ isDraft: true })], d);
    assert(d.calls.length === 0, d.calls.join());
  });
  t('fork is untouched', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ isCrossRepository: true })], d);
    assert(d.calls.length === 0, d.calls.join());
  });
  t('recently touched PR is skipped', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ updatedAt: '2026-11-19T11:55:00Z' })], d);
    assert(d.calls.length === 0, d.calls.join());
  });
  t('no-longer-DIRTY PR loses the label; unlabelled CLEAN PR is left alone', async () => {
    const d = mkDeps({ ok: true, files: [] });
    await processAll([mk({ number: 7, mergeStateStatus: 'CLEAN', labels: [LABEL] }), mk({ number: 8, mergeStateStatus: 'CLEAN' })], d);
    assert(d.calls.join() === 'unlabel#7', d.calls.join());
  });
  t('cap: only 5 rebases per run', async () => {
    const d = mkDeps({ ok: true, files: [] });
    const prs = [1, 2, 3, 4, 5, 6, 7].map((n) => mk({ number: n }));
    const rep = await processAll(prs, d);
    assert(d.calls.filter((c) => c.startsWith('rebase')).length === 5, d.calls.join());
    assert(rep[6].reason.startsWith('cap'), 'row 7 reports the cap');
  });
  t('dry run writes nothing', async () => {
    const d = mkDeps({ ok: false, files: ['a.ts'] });
    await processAll([mk({}), mk({ number: 2, mergeStateStatus: 'CLEAN', labels: [LABEL] })], d, { dryRun: true });
    assert(d.calls.join() === 'rebase#1', d.calls.join());
  });
  t('repo name reaches the GraphQL query (parseRepoSlug returns name, not repo)', async () => {
    const realFetch = globalThis.fetch;
    let vars = null;
    globalThis.fetch = async (url, init) => {
      if (String(url).endsWith('/graphql')) vars = JSON.parse(init.body).variables;
      return { ok: true, status: 200, json: async () => ({ data: { repository: { pullRequests: { nodes: [] } } } }) };
    };
    try {
      const code = await main(['--dry-run'], { GITHUB_TOKEN: 'x', GITHUB_REPOSITORY: 'acme/widgets' });
      assert(code === 0, 'exit ' + code);
      assert(vars && vars.owner === 'acme' && vars.name === 'widgets', JSON.stringify(vars));
    } finally {
      globalThis.fetch = realFetch;
    }
  });
  t('no token -> exit 2, not 0', async () => {
    assert((await main([], {})) === 2, 'exit code');
  });
  t('real git: clean rebase ok, conflicting rebase reports files and aborts', async () => {
    const { mkdtempSync, writeFileSync, rmSync } = await import('node:fs');
    const { tmpdir } = await import('node:os');
    const { join } = await import('node:path');
    const root = mkdtempSync(join(tmpdir(), 'rebase-st-'));
    try {
      const g = (cwd, ...a) => execFileSync('git', ['-c', 'user.email=t@t', '-c', 'user.name=t', ...a], { cwd, encoding: 'utf8', stdio: 'pipe' });
      const origin = join(root, 'origin.git');
      const w = join(root, 'w');
      execFileSync('git', ['init', '--quiet', '--bare', '-b', 'main', origin]);
      execFileSync('git', ['clone', '--quiet', origin, w], { stdio: 'pipe' });
      writeFileSync(join(w, 'f.txt'), 'base\n');
      g(w, 'add', '.'); g(w, 'commit', '-qm', 'base'); g(w, 'push', '-q', 'origin', 'HEAD:main');
      for (const [br, file, text] of [['clean', 'g.txt', 'x\n'], ['bad', 'f.txt', 'mine\n']]) {
        g(w, 'checkout', '-q', '-B', br, 'origin/main');
        writeFileSync(join(w, file), text);
        g(w, 'add', '.'); g(w, 'commit', '-qm', br); g(w, 'push', '-q', 'origin', br);
      }
      g(w, 'checkout', '-q', '-B', 'main', 'origin/main');
      writeFileSync(join(w, 'f.txt'), 'theirs\n');
      g(w, 'commit', '-qam', 'main moves'); g(w, 'push', '-q', 'origin', 'main');
      const run = (args, cwd) => g(cwd, ...args);
      const ok = gitRebase({ headRefName: 'clean' }, w, run);
      assert(ok.ok === true, 'clean rebase should succeed');
      const bad = gitRebase({ headRefName: 'bad' }, w, run);
      assert(bad.ok === false && bad.files.join() === 'f.txt', 'conflict files: ' + bad.files.join());
      assert(g(w, 'status', '--porcelain').trim() === '', 'rebase aborted, tree clean');
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  let failed = 0;
  for (const [name, fn] of cases) {
    try {
      await fn();
      console.log('  ok   ' + name);
    } catch (e) {
      failed += 1;
      console.log('  FAIL ' + name + ' -- ' + e.message);
    }
  }
  console.log((failed ? 'FAIL' : 'PASS') + ' self-test -- ' + cases.length + ' cases');
  return failed === 0 ? 0 : 1;
}

if (isEntryPoint(import.meta.url)) {
  process.exitCode = process.argv.includes('--self-test') ? await selfTest() : await main(process.argv.slice(2));
}
