"""Renders journey-grid.json into the table section of JOURNEY-GRID.md.

journey-grid.json is the source. Edit the rows there, then run:
    python3 docs/account-system/build_grid.py
The proposed CI check (PLAN.md PR-1) reads the same JSON.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
GRID = json.loads((HERE / "journey-grid.json").read_text(encoding="utf-8"))
START = "<!-- GRID:START (generated by build_grid.py from journey-grid.json; do not edit by hand) -->"
END = "<!-- GRID:END -->"


def cov(row):
    if not row["covered_by"]:
        return "**MISSING**"
    return "; ".join(f'{c["kind"]}:{c["ref"]}' for c in row["covered_by"])


def render():
    out = [START, ""]
    for group in GRID["groups"]:
        out.append(f'### {group["title"]}')
        out.append("")
        out.append("| ID | State | Action | END | Covered by | Gate | Prod |")
        out.append("|---|---|---|---|---|---|---|")
        for row in GRID["rows"]:
            if row["entry"] != group["entry"]:
                continue
            end = row["end"] + (f' ({row["decision"]})' if row.get("decision") else "")
            out.append(
                f'| `{row["id"]}` | {row["state"]} | {row["action"]} | {end} | {cov(row)} | '
                f'{row["coverage"]} | {row["people"]} |'
            )
        out.append("")
    out.append(END)
    return "\n".join(out)


md_path = HERE / "JOURNEY-GRID.md"
md = md_path.read_text(encoding="utf-8")
head, rest = md.split(START, 1)
_, tail = rest.split(END, 1)
md_path.write_text(head + render() + tail, encoding="utf-8")
print(f'{len(GRID["rows"])} rows rendered')
