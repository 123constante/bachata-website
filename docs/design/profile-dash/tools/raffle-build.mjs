// Builds organiser-raffle-option-{a,b}.html from raffle-src/ (shared core + one layout file each; base CSS from team-src).
// Usage: node docs/design/profile-dash/tools/raffle-build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => readFileSync(resolve(here, 'raffle-src', f), 'utf8');
const t = (f) => readFileSync(resolve(here, 'team-src', f), 'utf8');
const css = t('base.css') + t('team.css') + src('raffle.css');
for (const o of ['a', 'b']) {
  const lay = src(`${o}.js`);
  const title = lay.match(/const TITLE='([^']+)'/)[1];
  const html = `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Organiser Raffle ${o.toUpperCase()}</title>
<!-- GENERATED by tools/raffle-build.mjs from tools/raffle-src/ (+ team-src/base.css, team.css) (edit there). Organiser Raffle tab option ${o.toUpperCase()} (admin #1535 follow-up).
     Tokens, fonts, strip and tabs from organiser-option-a.html. Open #<shape> (${'empty normal huge off confirmOpen open confirmClose locked closed drawn nodraw cancelled draft contributor failed loading error'}); add &shot for a bare 390x844
     frame; &sheet=invite&m=find|link|email, &sheet=person&of=N, &sheet=remove&of=Nlist shows the Events list without the sheet. -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:wght@600;700&family=DM+Sans:wght@400;500;600&display=swap">
<style>
${css}</style>
</head>
<body>
<div class="wrap">
  <h1>${title}</h1>
  <div class="ctl"><span class="lbl">Shape</span><div class="seg" id="shseg"></div></div>
  <div class="frame" id="frame"></div>
  <p class="cap foot" id="foot"></p>
</div>
<script>
${lay}
document.getElementById('foot').innerHTML=FOOT;
${src('core.js')}</script>
</body>
</html>
`;
  writeFileSync(resolve(here, '..', `organiser-raffle-option-${o}.html`), html);
}
console.log('built a, b');
