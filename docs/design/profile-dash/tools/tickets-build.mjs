// Builds organiser-tickets-option-{a,b}.html from tickets-src/ (shared core + one layout file each).
// Usage: node docs/design/profile-dash/tools/tickets-build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => readFileSync(resolve(here, 'tickets-src', f), 'utf8');
const css = readFileSync(resolve(here, 'team-src', 'base.css'), 'utf8') + src('tickets.css');
for (const o of ['a', 'b']) {
  const lay = src(`${o}.js`);
  const title = lay.match(/const TITLE='([^']+)'/)[1];
  const html = `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Organiser Tickets ${o.toUpperCase()}</title>
<!-- GENERATED by tools/tickets-build.mjs from tools/tickets-src/ (edit there). Organiser Tickets tab option ${o.toUpperCase()} (admin #1535 follow-up).
     Tokens, fonts, strip and tabs from organiser-option-a.html. Open #<shape> (${'empty nostripe stripewait normal manager ownerhidden contributor huge guests guestsmgr refund refundok refunddenied price pricelocked pricereq approve payout loading error'}); add &shot for a bare 390x844
     frame; &seg=sell|orders|money (B), &sheet=type|guests|refund|payout&of=N, &amt=part. -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:wght@600;700&family=DM+Sans:wght@400;500;600&display=swap">
<style>
${css}</style>
</head>
<body>
<div class="wrap">
  <h1>${title}</h1>
  <div class="ctl"><span class="lbl">Shape</span><div class="seg" id="shseg"></div></div>
  <div class="frame" id="frame"></div>
  <p class="cap foot" id="foot"></p>
</div>
<script>
${lay}
document.getElementById('foot').innerHTML=FOOT;
${src('core.js')}</script>
</body>
</html>
`;
  writeFileSync(resolve(here, '..', `organiser-tickets-option-${o}.html`), html);
}
console.log('built a, b');
