// Builds organiser-guest-list-option-{a,b}.html from guest-src/ (shared core + one layout file each).
// Usage: node docs/design/profile-dash/tools/guest-build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => readFileSync(resolve(here, 'guest-src', f), 'utf8');
const css = readFileSync(resolve(here, 'team-src', 'base.css'), 'utf8') + src('guest.css'); // shared shell tokens from the Team round
for (const o of ['a', 'b']) {
  const lay = src(`${o}.js`);
  const title = lay.match(/const TITLE='([^']+)'/)[1];
  const html = `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Organiser Guest list ${o.toUpperCase()}</title>
<!-- GENERATED by tools/guest-build.mjs from tools/guest-src/ (edit there). Organiser Guest list tab option ${o.toUpperCase()} (admin #1535 follow-up).
     Tokens, fonts, strip and tabs from organiser-events-option-a.html. Open #<shape> (entry entrysheet off empty normal huge full closed door past cancelled contributor loading error teamonly dancer dancerin); add &shot for a bare 390x844
     frame; &sheet=add|settings|link|qr, &sheet=person&of=N, &sheet=remove&of=N; &view=names|door|settings (B); &v=team (privacy variant). -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:wght@600;700&family=DM+Sans:wght@400;500;600&display=swap">
<style>
${css}</style>
</head>
<body>
<div class="wrap">
  <h1>${title}</h1>
  <div class="ctl"><span class="lbl">Shape</span><div class="seg" id="shseg"></div></div>
  <div class="frame" id="frame"></div>
  <p class="cap foot" id="foot"></p>
</div>
<script>
${lay}
document.getElementById('foot').innerHTML=FOOT;
${src('core.js')}</script>
</body>
</html>
`;
  writeFileSync(resolve(here, '..', `organiser-guest-list-option-${o}.html`), html);
}
console.log('built a, b');
